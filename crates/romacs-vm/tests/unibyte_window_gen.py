#!/usr/bin/env python3
"""Generate unibyte_window.el: a window showing a unibyte buffer.

A file visited by `find-file-literally', and a shown buffer made unibyte
with `set-buffer-multibyte', hold bytes of every kind: ASCII, a UTF-8
sequence that stays two bytes, raw bytes shown as octal escapes, control
characters and tabs, in short lines and in lines long enough to continue
or truncate; a multibyte buffer holding the same text as raw bytes is the
comparison.  Each runs motion, scrolling and an edit with
`scroll-conservatively' 0 and 101, reading the window's start, point, ends
and point's column and row.

It reuses point_visibility.el's frame and step functions, so that
tests/point_visibility.rs replays it the same way against pinned GNU X11's
answers (child_frames_oracle.py --probe unibyte_window.el).

usage: unibyte_window_gen.py
"""
from point_visibility_gen import HERE, PRELUDE

DEFS = r'''(defun pv-text () (let (lines) (dotimes (i 91) (push (pcase (% i 6) (0 (format "%03d plain line" i)) (1 (format "%03d caf\303\251 \377\200 end" i)) (2 (format "%03d\ttab\001\177 ctl" i)) (3 (concat (format "%03d " i) (apply #'unibyte-string (mapcar (lambda (k) (+ 128 (% k 128))) (number-sequence 0 59))))) (4 "") (5 (format "%03d %s" i (make-string 130 ?w)))) lines)) (mapconcat #'identity (nreverse lines) "\n")))
(defun pv-state () (mapcar (lambda (w) (list (window-hscroll w) (window-start w) (window-point w) (window-end w) (window-end w t) (let ((p (posn-at-point (window-point w) w))) (and p (posn-col-row p))) (with-current-buffer (window-buffer w) enable-multibyte-characters))) (window-list nil 'never (frame-first-window))))
(defun uw-file () (let ((file (make-temp-file "uw"))) (let ((coding-system-for-write 'no-conversion)) (with-temp-file file (set-buffer-multibyte nil) (insert (pv-text)))) file))
(defun uw-literal (config) (let ((file (uw-file))) (pv-begin config) (find-file-literally file) (delete-file file) (pv-run config) (setq last-command nil)))
(defun uw-toggled (config) (pv-begin config) (with-current-buffer "pv" (set-buffer-multibyte nil) (goto-char (point-min))) (setq last-command nil))
(defun uw-mode-line () (mapcar #'substring-no-properties (list (with-current-buffer "pv" (insert "z") (format-mode-line "%* %l %c")) (with-current-buffer (get-buffer-create "unshown") (erase-buffer) (set-buffer-multibyte nil) (insert "q\377\n") (format-mode-line "%* %b" nil nil (current-buffer))))))
(defun uw-multibyte (config) (pv-begin config) (with-current-buffer "pv" (goto-char (point-min))) (setq last-command nil))
'''

STEPS = (["'(next-line)"] * 8 + ["'(forward-char)"] * 12 + ["'(end-of-line)", "'(next-line)", "'(beginning-of-line)"]
         + ["'(next-line)"] * 20 + ["'(scroll-up-command)", "'(scroll-up-command)", "'(scroll-down-command)", "'(previous-line)",
            "'(end-of-buffer)", "'(previous-line)", "'((call insert \"\\377x\"))", "'(delete-backward-char)", "'((call recenter 3))",
            "'(beginning-of-buffer)", "'((call insert \"abc\"))", "'((call narrow-to-region 200 900))", "'(end-of-buffer)",
            "'(beginning-of-buffer)", "'(widen beginning-of-buffer)"])


def main():
    header = (';;; unibyte_window.el --- a window showing a unibyte buffer  -*- lexical-binding: t -*-\n'
              ';; Generated by unibyte_window_gen.py; answered by pinned GNU X11\n'
              ';; (child_frames_oracle.py --probe), replayed by tests/point_visibility.rs.\n')
    out = [header, PRELUDE[PRELUDE.index('(progn'):], DEFS]
    for how in ('literal', 'toggled', 'multibyte'):
        for truncate in ('nil', 't'):
            for conservative in (0, 101):
                config = f'(set scroll-conservatively {conservative}) (set scroll-margin 0) (setq-local truncate-lines {truncate})'
                out.append(f';; {how}-{truncate}-{conservative}\n')
                out.append(f"(progn (uw-{how} '({config})) (pv-step nil))\n")
                out.extend(f'(pv-step {step})\n' for step in STEPS)
                out.append('(uw-mode-line)\n')
    (HERE / 'unibyte_window.el').write_text(''.join(out))


if __name__ == '__main__':
    main()
