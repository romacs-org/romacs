#!/usr/bin/env python3
"""Generate scroll_invisible.el: C-n from the top of a buffer past two
invisible blocks to its end, then C-p back, with `scroll-conservatively' 0, 5 and 101
and `scroll-margin' 0 and 3.  The blocks hide whole lines (as a collapsed
message part does) and a heading's subtree from its line's end (as org
folding does), by an `invisible' text property, an overlay, or a symbol
in `buffer-invisibility-spec'.  Some lines are long enough to continue.
The last kind hides by property in a buffer ending in a newline, whose
ZV shows on a row of its own below the bottom margin, with lines continued
and truncated; their keys reach ZV.

It reuses point_visibility.el's frame and step functions, so that
tests/point_visibility.rs replays it the same way against pinned GNU X11's
answers (child_frames_oracle.py --probe scroll_invisible.el).

usage: scroll_invisible_gen.py
"""
import pathlib

from point_visibility_gen import HERE, PRELUDE

DEFS = r'''(defun pv-text () (let ((lines nil)) (dotimes (i 120) (push (if (= (% i 10) 5) (format "%03d long %s" (1+ i) (make-string 150 ?l)) (format "%03d line" (1+ i))) lines)) (mapconcat #'identity (nreverse lines) "\n")))
(defun si-pos (line eol) (save-excursion (goto-char (point-min)) (forward-line (1- line)) (if eol (line-end-position) (point))))
(defun si-hide (kind from to) (pcase kind ((or 'property 'newline 'truncated) (put-text-property from to 'invisible t)) ('overlay (overlay-put (make-overlay from to) 'invisible t)) ('spec (put-text-property from to 'invisible 'si-fold) (add-to-invisibility-spec 'si-fold))))
(defun si-begin (config kind) (pv-begin config) (with-current-buffer "pv" (si-hide kind (si-pos 14 nil) (si-pos 42 nil)) (si-hide kind (si-pos 60 t) (si-pos 75 t)) (when (memq kind '(newline truncated)) (goto-char (point-max)) (insert "\n")) (goto-char (point-min))) (setq last-command nil))
'''

KINDS = ['property', 'overlay', 'spec', 'newline', 'truncated']
STEPS = 85


def main():
    header = (';;; scroll_invisible.el --- scrolling past invisible text  -*- lexical-binding: t -*-\n'
              ';; Generated by scroll_invisible_gen.py; answered by pinned GNU X11\n'
              ';; (child_frames_oracle.py --probe), replayed by tests/point_visibility.rs.\n')
    out = [header, PRELUDE[PRELUDE.index('(progn'):], DEFS]
    for kind in KINDS:
        for conservative in (0, 5, 101):
            for margin in (0, 3):
                config = f'(set scroll-conservatively {conservative}) (set scroll-margin {margin}) (setq-local truncate-lines {"t" if kind == "truncated" else "nil"})'
                out.append(f';; {kind}-{conservative}-{margin}\n')
                out.append(f"(progn (si-begin '({config}) '{kind}) (pv-step nil))\n")
                steps = STEPS + 40 if kind in ('newline', 'truncated') else STEPS
                out.extend("(pv-step '(next-line))\n" for _ in range(steps))
                out.extend("(pv-step '(previous-line))\n" for _ in range(steps))
    (HERE / 'scroll_invisible.el').write_text(''.join(out))


if __name__ == '__main__':
    main()
