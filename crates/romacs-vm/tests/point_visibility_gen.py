#!/usr/bin/env python3
"""Generate point_visibility.el: randomized command sequences over long,
short, tabbed and wide lines in split, narrow and divided windows, with
truncation, line numbers and GNU's scrolling options varied per sequence.

Each `(pv-step ...)' line runs commands, lets redisplay run and records
every window's hscroll, start, point and body width.  Pinned GNU X11
answers the probe (child_frames_oracle.py --probe point_visibility.el);
tests/point_visibility.rs replays it over the real layout and compares,
and checks after every step that each cursor lies in its text area.

usage: point_visibility_gen.py [--seed N] [--sequences N] [--steps N]
"""
import argparse
import pathlib
import random

HERE = pathlib.Path(__file__).resolve().parent

PRELUDE = r''';;; point_visibility.el --- point visibility on both axes  -*- lexical-binding: t -*-
;; Generated by point_visibility_gen.py; answered by pinned GNU X11
;; (child_frames_oracle.py --probe), replayed by tests/point_visibility.rs.
;; A frame 100 columns of text wide and 24 lines tall, with fringes and
;; dividers a column wide, so that every window is whole columns in any
;; font.  Wide characters show in the `wide' sequences only, whose
;; widths are the fonts' (no GNU comparison there).
(progn (setq window-resize-pixelwise nil) (when (fboundp 'x-create-frame) (message nil) (setq frame-inhibit-implied-resize t frame-resize-pixelwise t) (menu-bar-mode -1) (tool-bar-mode -1) (scroll-bar-mode -1) (blink-cursor-mode -1) (set-frame-font (font-spec :family "Iosevka" :size 19) nil t) (modify-frame-parameters nil `((internal-border-width . 0) (left-fringe . ,(frame-char-width)) (right-fringe . ,(frame-char-width)))) (set-frame-size nil (* 100 (frame-char-width)) (* 24 (frame-char-height)) t) (dotimes (_ 100) (unless (= (frame-text-width) (* 100 (frame-char-width))) (sit-for 0.02)))) (modify-frame-parameters nil `((left-fringe . ,(frame-char-width)) (right-fringe . ,(frame-char-width)))) (dolist (face '(mode-line mode-line-active mode-line-inactive header-line)) (set-face-attribute face nil :box nil :inherit nil :height 'unspecified :family 'unspecified :overline nil :underline nil)) (setq-default mode-line-format "%b" cursor-in-non-selected-windows t) (list (frame-text-cols) (frame-text-lines)))
(defvar pv-wide nil)
(defun pv-text () (let ((lines nil)) (dotimes (i 120) (push (pcase (% i 9) (0 (format "%03d * commit %s %s" i (make-string 40 ?h) (make-string (+ 60 (* 7 (% i 13))) ?s))) (1 "") (2 (format "%03d short" i)) (3 (concat (format "%03d" i) "\ttab\t\ttabs " (make-string (* 11 (% i 7)) ?t) "\tend")) (4 (format "%03d wide %s tail %s" i (apply #'string (make-list (+ 10 (% i 11)) (if pv-wide ?日 ?W))) (make-string 50 ?w))) (5 (make-string (+ 95 (% i 10)) ?x)) (6 (format "%03d mid %s" i (make-string 70 ?m))) (7 (format "%03d" i)) (_ (format "%03d %s" i (make-string 300 ?l)))) lines)) (mapconcat #'identity (nreverse lines) "\n")))
(defun pv-do (c) (condition-case nil (pcase c (`(set ,var ,val) (set var val)) (`(setq-local ,var ,val) (set (make-local-variable var) val)) (`(call ,f . ,args) (apply f args)) (`(frame ,params) (modify-frame-parameters nil params)) ((pred symbolp) (setq this-command c) (call-interactively c) (setq last-command c))) (error nil)))
(defun pv-run (cmds) (mapc #'pv-do cmds) nil)
(defun pv-state () (mapcar (lambda (w) (list (window-hscroll w) (window-start w) (window-point w) (window-body-width w) (window-body-height w))) (window-list nil 'never (frame-first-window))))
(defun pv-dividers () (modify-frame-parameters nil `((right-divider-width . ,(frame-char-width)) (bottom-divider-width . ,(frame-char-height)))))
(defun pv-step (cmds) (pv-run cmds) (redisplay t) (pv-state))
(defun pv-begin (config) (modify-frame-parameters nil '((right-divider-width . 0) (bottom-divider-width . 0))) (setq pv-wide nil) (let ((ignore-window-parameters t)) (delete-other-windows)) (when (get-buffer "pv") (kill-buffer "pv")) (switch-to-buffer (get-buffer-create "pv")) (pv-run config) (with-current-buffer "pv" (insert (pv-text)) (goto-char (point-min))) (setq last-command nil))
'''

COMMANDS = [
    'end-of-line', 'end-of-line', 'beginning-of-line', 'next-line', 'next-line', 'next-line',
    'previous-line', 'previous-line', 'scroll-up-command', 'scroll-down-command',
    'end-of-buffer', 'beginning-of-buffer', 'other-window',
    '(call forward-char 9)', '(call forward-char 40)', '(call backward-char 30)',
    '(call move-to-column 130)', '(call move-to-column 20)', '(call forward-line 5)',
    'scroll-left', 'scroll-right', '(call set-window-hscroll nil 12)',
]
OPTIONS = [
    ['(setq-local truncate-lines t)', '(setq-local truncate-lines nil)'],
    ['(set truncate-partial-width-windows 50)', '(set truncate-partial-width-windows nil)'],
    ['(setq-local display-line-numbers nil)', '(setq-local display-line-numbers t)'],
    ['(set auto-hscroll-mode t)', '(set auto-hscroll-mode current-line)', '(set auto-hscroll-mode nil)'],
    ['(set hscroll-margin 5)', '(set hscroll-margin 0)', '(set hscroll-margin 2)'],
    ['(set hscroll-step 0)', '(set hscroll-step 4)', '(set hscroll-step 0.25)'],
    ['(set scroll-margin 0)', '(set scroll-margin 3)'],
    ['(set scroll-conservatively 0)', '(set scroll-conservatively 101)'],
]
LAYOUTS = [
    [], ['split-window-right'], ['split-window-below'], ['split-window-right', 'split-window-below'],
    ['split-window-right', '(call shrink-window-horizontally 20)'],
    ['split-window-right', 'split-window-right'],
]
CHROME = ['(call pv-dividers)']


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--seed', type=int, default=20261102)
    ap.add_argument('--sequences', type=int, default=24)
    ap.add_argument('--wide', type=int, default=6)
    ap.add_argument('--steps', type=int, default=24)
    args = ap.parse_args()
    rng = random.Random(args.seed)
    out = [PRELUDE]
    for n in range(args.sequences + args.wide):
        wide = n >= args.sequences
        config = [rng.choice(group) for group in OPTIONS] + (['(set pv-wide t)'] if wide else [])
        if rng.random() < 0.3:
            config += CHROME
        config += rng.choice(LAYOUTS)
        out.append(f";; {'wide' if wide else 'sequence'}-{n}\n")
        out.append(f"(progn (pv-begin '({' '.join(config)})) (pv-step nil))\n")
        for _ in range(args.steps):
            cmds = [rng.choice(COMMANDS) for _ in range(rng.choice([1, 1, 1, 2]))]
            out.append(f"(pv-step '({' '.join(cmds)}))\n")
    (HERE / 'point_visibility.el').write_text(''.join(out))


if __name__ == '__main__':
    main()
