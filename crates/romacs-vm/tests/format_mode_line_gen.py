#!/usr/bin/env python3
"""Generate format_mode_line.el: `format-mode-line' of another buffer reads
that buffer's point, not the selected window's.

Buffers other than the window's, with point on several lines and columns,
one narrowed, are formatted beside the window's own, with the window on a
different line.

It reuses point_visibility.el's frame and step functions, so that
tests/point_visibility.rs replays it the same way against pinned GNU X11's
answers (child_frames_oracle.py --probe format_mode_line.el).

usage: format_mode_line_gen.py
"""
from point_visibility_gen import HERE, PRELUDE

DEFS = r'''(defun pv-text () (mapconcat (lambda (i) (format "%03d line" i)) (number-sequence 1 40) "\n"))
(defun fm-other (lines line column) (with-current-buffer (get-buffer-create "fm") (widen) (erase-buffer) (dotimes (i lines) (insert (format "row %d of the other buffer\n" i))) (goto-char (point-min)) (forward-line line) (move-to-column column) (current-buffer)))
(defun fm-text (&optional buffer) (substring-no-properties (format-mode-line "%l %c %b" nil nil buffer)))
'''

FORMS = [
    "(fm-text)",
    "(fm-text (fm-other 10 0 0))",
    "(fm-text (fm-other 10 6 4))",
    "(fm-text (fm-other 10 9 11))",
    "(fm-text (fm-other 60 50 2))",
    "(fm-text (fm-other 3 2 0))",
    "(let ((b (fm-other 20 12 3))) (with-current-buffer b (narrow-to-region (save-excursion (forward-line -4) (point)) (point-max))) (fm-text b))",
    "(with-current-buffer (fm-other 10 6 4) (substring-no-properties (format-mode-line \"%l %c\")))",
    "(progn (with-current-buffer \"pv\" (goto-char (point-max))) (redisplay t) (fm-text (fm-other 10 6 4)))",
    "(let* ((b (fm-other 10 6 4)) (text (progn (with-current-buffer b (set-buffer-multibyte nil)) (fm-text b)))) (with-current-buffer b (set-buffer-multibyte t)) text)",
    "(fm-text)",
]


def main():
    header = (';;; format_mode_line.el --- format-mode-line of another buffer  -*- lexical-binding: t -*-\n'
              ';; Generated by format_mode_line_gen.py; answered by pinned GNU X11\n'
              ';; (child_frames_oracle.py --probe), replayed by tests/point_visibility.rs.\n')
    out = [header, PRELUDE[PRELUDE.index('(progn'):], DEFS]
    config = "'((set scroll-conservatively 0) (set scroll-margin 0) (setq-local truncate-lines nil))"
    out.append(';; other-buffer\n')
    out.append(f"(progn (pv-begin {config}) (pv-step '(next-line next-line next-line)))\n")
    out.extend(f'{form}\n' for form in FORMS)
    (HERE / 'format_mode_line.el').write_text(''.join(out))


if __name__ == '__main__':
    main()
