#!/usr/bin/env python3
"""Generate the bundled packages' autoloads with GNU's `loaddefs-generate'.

The package directories are the subdirectories of the roots LISP-BUNDLED.json
declares, in load-path order; a root's own files are preloaded runtime Lisp.
Each is scanned as package.el scans an installed package: its own directory
holds the output, so every autoload names its library by bare load name.  A
private symlink view gives each directory that position without writing into
the source tree.  The pinned GNU oracle runs the generator; the result is
concatenated, as package-quickstart concatenates installed packages'
autoloads, under a fixed header with no timestamps or absolute paths.
"""
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
LAYOUT = 'LISP-BUNDLED.json'
OUTPUT = '=loaddefs.el'
SECTION = '\n\f\n;;; Generated autoloads from '
END = '\f\n;;; End of scraped data'


def layout(root):
    return json.loads((root / LAYOUT).read_text())


def directories(root):
    """The package directories: each root's immediate subdirectories, in runtime_load_path
    order.  A root itself holds Romacs's preloaded runtime Lisp, not a package."""
    found = []
    for entry in layout(root)['roots']:
        base = root / entry['path']
        if base.is_dir():
            found.extend(sorted(p for p in base.iterdir() if p.is_dir() and p.name not in entry['exclude']))
    return found


def header(name):
    return f''';;; {name} --- Bundled packages' autoloads (do not edit)  -*- lexical-binding: t -*-

;; SPDX-License-Identifier: GPL-3.0-or-later

;;; Commentary:

;; Generated by tools/bundled_autoloads.py from the package directories
;; {LAYOUT} declares: GNU's `loaddefs-generate', run by the pinned GNU
;; Emacs, scans each one as package.el scans an installed package.  The
;; --loadup launch loads this file after GNU's loadup and before the user's
;; init, as `package-activate-all' loads installed packages' autoloads.
;; scripts/check-derived detects and regenerates a stale copy.

;;; Code:
'''


def trailer(name):
    return f'''
\f
;;; End of scraped data

(provide '{name.removesuffix('.el')})

;; Local Variables:
;; version-control: never
;; no-byte-compile: t
;; no-update-autoloads: t
;; no-native-compile: t
;; coding: utf-8-emacs-unix
;; End:

;;; {name} ends here
'''


def sections(text, source):
    start, end = text.find(SECTION), text.rfind(END)
    if start < 0 or end < start:
        raise ValueError(f'{source}: loaddefs-generate output has no autoload sections')
    return text[start:end].rstrip('\n') + '\n'


def generate(root):
    sys.path.insert(0, str(ROOT / 'scripts'))
    import gnu_oracle
    oracle = gnu_oracle.require()['path']
    output = root / layout(root)['autoloads']
    dirs = directories(root)
    with tempfile.TemporaryDirectory(prefix='romacs-autoloads-', dir=os.environ.get('TMPDIR')) as temp:
        views = []
        for index, directory in enumerate(dirs):
            view = Path(temp) / f'{index:03d}'
            view.mkdir()
            for file in sorted(directory.iterdir()):
                if file.is_file() and file != output:
                    (view / file.name).symlink_to(file)
            views.append(view)
        forms = ' '.join(f'(loaddefs-generate {json.dumps(str(v))} {json.dumps(str(v / OUTPUT))} nil nil nil t)'
                         for v in views)
        env = {'PATH': '/usr/bin:/bin', 'HOME': temp, 'LANG': 'C.UTF-8', 'TZ': 'UTC'}
        subprocess.run([oracle, '-Q', '--batch', '-l', 'loaddefs-gen', '--eval', f'(progn {forms})'],
                       env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
        body = []
        for directory, view in zip(dirs, views):
            generated = view / OUTPUT
            if generated.exists():
                relative = directory.relative_to(root).as_posix()
                body.append(f'\n\f\n;;; Directory {relative}\n' + sections(generated.read_text(encoding='utf-8'), relative))
    output.write_text(header(output.name) + ''.join(body) + trailer(output.name), encoding='utf-8')


def main():
    root = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else Path.cwd()
    try:
        generate(root)
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        detail = exc.stderr.decode(errors='replace')[-2000:] if getattr(exc, 'stderr', None) else ''
        print(f'bundled_autoloads: {exc}\n{detail}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
