#!/usr/bin/env python3
"""Regenerate literal folding data with the active Rust Unicode tables.

Run through neomacs-slot; the exhaustive Rust regression checks toolchain drift.
"""
from pathlib import Path
import hashlib
import os
import subprocess
import tempfile

root = Path(__file__).resolve().parent.parent
source = (root / 'crates/romacs-core/src/emacs_core/lisp/native/builtins/strings.rs').read_text()
start = source.index('fn preserve_emacs_downcase_payload(')
functions = source[start:source.index('\n/// Build the casing', start)]
version = subprocess.check_output(['rustc', '--version'], text=True).strip()
program = functions + r'''
fn main() {
    let mut mapping = std::collections::BTreeMap::new();
    for c in 0..=0x10ffffu32 {
        let canonical = downcase_char_code_emacs_compat(c as i64) as u32;
        if c != canonical { mapping.insert(c, canonical); }
    }
    for c in mapping.values().copied().collect::<Vec<_>>() {
        mapping.entry(c).or_insert(c);
    }
    let mut groups: std::collections::BTreeMap<u32, Vec<u32>> = std::collections::BTreeMap::new();
    for (&c, &canonical) in &mapping { groups.entry(canonical).or_default().push(c); }
    let mut next = std::collections::BTreeMap::new();
    for group in groups.values() {
        for (i, &c) in group.iter().enumerate() { next.insert(c, group[(i + 1) % group.len()]); }
    }
    println!("pub(super) static STANDARD_FOLD: &[(u32, u32, u32)] = &[");
    for (c, canonical) in mapping { println!("    (0x{c:X}, 0x{canonical:X}, 0x{:X}),", next[&c]); }
    println!("];");
}
'''
with tempfile.TemporaryDirectory(prefix='standard-fold-', dir=os.environ['TMPDIR']) as directory:
    rs = Path(directory) / 'generate.rs'
    exe = Path(directory) / 'generate'
    rs.write_text(program)
    subprocess.run(['rustc', '--edition=2024', str(rs), '-o', str(exe)], check=True)
    output = subprocess.check_output([str(exe)], text=True)
header = ('// Generated by scripts/generate-standard-fold.py; do not edit.\n'
          '// Entries: (code point, canonical, next equivalent); identity is implicit.\n'
          f'// Generator toolchain: {version}\n'
          f'// Extracted function source SHA-256: {hashlib.sha256(functions.encode()).hexdigest()}\n')
out = root / 'crates/romacs-core/src/emacs_core/text/regex/standard_fold.rs'
out.write_text(header + output)
subprocess.run(['rustfmt', '--edition', '2024', str(out)], check=True)
print(f'Generated {out.relative_to(root)} with {output.count("    (")} entries')
